/**
 * @param {Record<string, string>} values — строки экранированы вызывающим кодом (кроме служебных HTML-блоков ниже).
 */
function substitutePlaceholders(template, values) {
    let out = template;
    const merged = { ...values };
    for (const [key, val] of Object.entries(merged)) {
        const re = new RegExp(`\\{\\{${key}\\}\\}`, 'g');
        out = out.replace(re, val != null ? String(val) : '—');
    }
    if (/\{\{[a-z_]+\}\}/.test(out)) {
        console.warn('[ndaAgreementTextRu] Unsubstituted placeholders remain in NDA template');
    }
    return out;
}

function buildNdaInnerHtml(values) {
    const offerHtml = buildOfferRelationHtml();
    const pdHtml = buildPersonalDataHtml();
    return substitutePlaceholders(NDA_INNER_HTML_TEMPLATE, {
        ...values,
        offer_relation_html: offerHtml,
        personal_data_html: pdHtml,
    }).trim();
}

