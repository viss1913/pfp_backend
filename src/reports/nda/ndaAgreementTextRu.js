/**
 * Связь с публичной офертой (если задан NDA_PUBLIC_OFFER_URL — подставляется адрес).
 */
function buildOfferRelationHtml() {
    const url = process.env.NDA_PUBLIC_OFFER_URL && String(process.env.NDA_PUBLIC_OFFER_URL).trim();
    if (url) {
        const esc = (s) =>
            String(s)
                .replace(/&/g, '&amp;')
                .replace(/</g, '&lt;')
                .replace(/>/g, '&gt;')
                .replace(/"/g, '&quot;');
        const hrefEsc = esc(url);
        return `<p>Настоящее Соглашение является неотъемлемой частью договора оказания консультационных услуг по финансовому планированию (Публичной оферты Консультанта), размещённой по адресу: <a href="${hrefEsc}">${esc(url)}</a>, и применяется ко всем отношениям Сторон, вытекающим из указанного договора.</p>`;
    }
    return `<p>Настоящее Соглашение распространяется на отношения Сторон в связи с использованием сервиса финансового планирования Консультанта и, при наличии у Консультанта публичной оферты в открытом доступе, по режиму конфиденциальности является её неотъемлемой частью.</p>`;
}

